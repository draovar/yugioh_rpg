// Generates data/pool.json: every card printed in a TCG product released on or before CUTOFF, plus/minus the
// hand-picked cards in data/pool-exceptions.json. Card lists come from YGOPRODeck (cached in vendor/ygoprodeck/;
// `--refresh` downloads them again), passcodes from BabelCDB (run `npm run fetch-data` first).
// Usage: npm run build-pool [-- --refresh]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

/** Premium Pack 2, the last TCG product before the first Synchros (5D's Starter Deck, August 2008). */
const CUTOFF = "2008-07-31";

const ROOT = path.resolve(import.meta.dirname, "../..");
const CACHE = path.join(ROOT, "vendor/ygoprodeck");
const API = "https://db.ygoprodeck.com/api/v7";
const refresh = process.argv.includes("--refresh");

async function cached(file, url) {
  const p = path.join(CACHE, file);
  if (refresh || !existsSync(p)) {
    console.log(`downloading ${url}`);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(p, await res.text());
  }
  return JSON.parse(readFileSync(p, "utf-8"));
}

const sets = await cached("cardsets.json", `${API}/cardsets.php`);
const allCards = (await cached("cardinfo.json", `${API}/cardinfo.php?misc=yes`)).data;

const db = new DatabaseSync(path.join(ROOT, "vendor/BabelCDB/cards.cdb"), { readOnly: true });
const byId = db.prepare("SELECT d.id, d.alias, t.name FROM datas d JOIN texts t ON t.id = d.id WHERE d.id = ?");
const byName = db.prepare("SELECT d.id FROM datas d JOIN texts t ON t.id = d.id WHERE t.name = ? AND d.alias = 0");

// YGOPRODeck's card id is sometimes an alt-art id (Monster Reborn: 83764719, the real passcode is 83764718), so take
// whichever of the card's image ids BabelCDB has as the base card. An alias with the same name is an alt art; one
// with another name is a card of its own that only counts as that name (Harpie Lady 1, A Legendary Ocean).
// None at all = a video-game-only promo.
function passcode(card) {
  const rows = card.card_images.map((img) => byId.get(img.id)).filter(Boolean);
  const base = rows.find((r) => !r.alias) ?? rows[0];
  if (!base) return null;
  return Number(base.alias && byId.get(base.alias)?.name === base.name ? base.alias : base.id);
}

const early = new Set(sets.filter((s) => s.tcg_date && s.tcg_date <= CUTOFF).map((s) => s.set_name));
const pool = new Set();
const noPasscode = [];
for (const card of allCards) {
  if (card.frameType === "token" || card.frameType === "skill") continue;
  if (!card.card_sets?.some((s) => early.has(s.set_name))) continue;
  const code = passcode(card);
  if (code) pool.add(code);
  else noPasscode.push(card.name);
}

const exceptions = JSON.parse(readFileSync(path.join(ROOT, "data/pool-exceptions.json"), "utf-8"));
const resolve = (name) => {
  const r = byName.get(name);
  if (!r) throw new Error(`pool-exceptions.json: no card named "${name}" in cards.cdb`);
  return Number(r.id);
};
for (const name of Object.keys(exceptions.add)) pool.add(resolve(name));
for (const name of Object.keys(exceptions.remove)) pool.delete(resolve(name));

const old = new Set(existsSync(path.join(ROOT, "data/pool.json"))
  ? JSON.parse(readFileSync(path.join(ROOT, "data/pool.json"), "utf-8")).cards : []);
const cards = [...pool].sort((a, b) => a - b);
const comment = `Generated by tools/data/build-pool.mjs (TCG products up to ${CUTOFF} + data/pool-exceptions.json); ` +
  "don't edit by hand. tools/data/build-data.mjs extracts only these (plus engine utility scripts) into public/data/.";
const rows = [];
for (let i = 0; i < cards.length; i += 12) rows.push("    " + cards.slice(i, i + 12).join(", "));
writeFileSync(path.join(ROOT, "data/pool.json"),
  `{\n  "_comment": ${JSON.stringify(comment)},\n  "cards": [\n${rows.join(",\n")}\n  ]\n}\n`);

console.log(`${early.size} TCG products up to ${CUTOFF} -> ${cards.length} cards ` +
  `(+${cards.filter((c) => !old.has(c)).length} / -${[...old].filter((c) => !pool.has(c)).length} vs the previous pool)`);
if (noPasscode.length) console.log(`skipped, not in cards.cdb (video-game promos): ${noPasscode.join(", ")}`);
